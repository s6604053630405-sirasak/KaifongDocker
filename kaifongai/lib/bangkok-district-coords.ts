/**
 * หาพิกัดของเขต จากชื่อที่เก็บใน DB (รองรับทั้งแบบมี/ไม่มีคำนำหน้า "เขต" และช่องว่างเกิน)
 * ถ้าชื่อในฐานข้อมูลไม่ตรงกับ key ในตารางนี้เป๊ะๆ (เช่นสะกดต่างกัน) ฟังก์ชันจะคืนค่า null
 * → แนะนำให้ log รายชื่อที่ lookup ไม่เจอ แล้วเติม alias เพิ่มในตารางด้านล่าง
 */
const DISTRICT_ALIASES: Record<string, string> = {
  // เผื่อชื่อในฐานข้อมูลสะกด/เขียนต่างจาก Wikipedia เล็กน้อย ให้เพิ่ม mapping ตรงนี้
  // ตัวอย่าง: "บางกอกน้อย ": "บางกอกน้อย",
};

export function getDistrictCoords(rawName: string | null | undefined): DistrictCoord | null {
  if (!rawName) return null;
  let name = rawName.trim();
  name = name.replace(/^เขต\s*/, ""); // ตัดคำว่า "เขต" นำหน้าออกถ้ามี
  name = DISTRICT_ALIASES[name] || name;
  return BANGKOK_DISTRICT_COORDS[name] || null;
}